"""Encode project-generated floral PNGs for LVGL without flattening alpha.

The original PNGs remain in firmware/assets/calendar-flowers. This build step
only resamples to display size, quantizes RGBA and losslessly compresses the
indexed pixel stream using the existing LVGL LZ4 decoder.
"""
from pathlib import Path
from struct import pack
import hashlib
import json

from PIL import Image
from lz4.block import compress, decompress

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'firmware/assets/calendar-flowers'
OUTPUT = ROOT / 'firmware/main/calendar_flowers.h'
NAMES = ('01-plum', '02-apricot', '03-peach', '04-peony', '05-paeonia',
         '06-gardenia', '07-lotus', '08-lily', '09-osmanthus',
         '10-chrysanthemum', '11-camellia', '12-narcissus')
WIDTH, HEIGHT, COLORS = 280, 252, 256
lines = ['// Generated by scripts/generate-calendar-flowers.py; project-created botanical artwork.',
         '#pragma once', '#include "lvgl.h"', '']
reports = []
for name in NAMES:
    source = ASSETS / (name + '.png')
    with Image.open(source) as original:
        rgba = original.convert('RGBA')
        assert rgba.getchannel('A').getextrema()[0] == 0, f'{name}: missing transparent background'
        rgba.thumbnail((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', (WIDTH, HEIGHT))
        canvas.alpha_composite(rgba, ((WIDTH - rgba.width) // 2, (HEIGHT - rgba.height) // 2))
    indexed = canvas.quantize(colors=COLORS, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    palette = indexed.getpalette('RGBA')
    palette.extend([0] * (1024 - len(palette)))
    bgra = bytes(v for i in range(256) for v in (palette[i*4+2], palette[i*4+1], palette[i*4], palette[i*4+3]))
    raw = bgra + indexed.tobytes()
    payload = compress(raw, mode='high_compression', compression=12, store_size=False)
    assert decompress(payload, uncompressed_size=len(raw)) == raw
    assert indexed.convert('RGBA').getchannel('A').getextrema()[0] == 0
    wire = pack('<III', 2, len(payload), len(raw)) + payload
    symbol = name.replace('-', '_')
    lines.append(f'static const uint8_t calendar_flower_{symbol}[] __attribute__((aligned(4))) = {{')
    for start in range(0, len(wire), 16):
        lines.append('    ' + ', '.join(f'0x{x:02x}' for x in wire[start:start+16]) + ',')
    lines.extend(['};', ''])
    reports.append({'name': name, 'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                    'encodedBytes': len(wire), 'rawBytes': len(raw), 'alpha': True})
lines.append('static const lv_image_dsc_t monthly_flower_images[] = {')
for name in NAMES:
    symbol = name.replace('-', '_')
    lines.extend(['    {', '        .header = {.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_I8,',
                  f'                   .flags=LV_IMAGE_FLAGS_COMPRESSED, .w={WIDTH}, .h={HEIGHT}, .stride={WIDTH}}},',
                  f'        .data_size=sizeof(calendar_flower_{symbol}), .data=calendar_flower_{symbol},', '    },'])
lines.extend(['};', ''])
total = sum(r['encodedBytes'] for r in reports)
assert total < 220000, f'Flower assets exceed remaining application space: {total}'
OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
(ASSETS / 'encoding.json').write_text(json.dumps({'width': WIDTH, 'height': HEIGHT, 'colors': COLORS, 'totalBytes': total,
                                                 'images': reports}, indent=2), encoding='utf-8')
print(f'CALENDAR_FLOWERS_OK 12 transparent images; {total} encoded bytes')
