"""Build the offline TAB5 dictionary from the pinned, vendored Apache-2.0 source."""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parents[1]
source = root / 'firmware/third_party/rime-pinyin-simp/pinyin_simp.dict.yaml'
expected = 'e341598343a0f0f2035bb1aafc34a7f3bb7887deeecb3f60796262aaa2983e6b'
assert hashlib.sha256(source.read_bytes()).hexdigest() == expected, 'Dictionary source changed'
entries = {}
for line in source.read_text(encoding='utf-8').splitlines():
    fields = line.split('\t')
    if len(fields) != 3:
        continue
    word, spelling, weight = fields
    syllables = spelling.split()
    key = ''.join(syllables)
    if not 1 <= len(word) <= 8 or len(key) > 32 or not re.fullmatch('[a-z]+', key):
        continue
    try:
        word.encode('gb2312')  # Match the bundled font; never offer missing glyphs.
    except UnicodeEncodeError:
        continue
    boundaries = 0
    end = 0
    for syllable in syllables[:-1]:
        end += len(syllable)
        boundaries |= 1 << end
    entry = (key, word, boundaries)
    entries[entry] = max(entries.get(entry, 0), int(weight))
ordered = sorted(entries, key=lambda e: (e[0], -entries[e], e[1], e[2]))


def string_pool(values):
    """Share NUL-terminated suffixes without runtime allocation or decoding."""
    pool, offsets = bytearray(), {}
    for value in sorted({v.encode('utf-8') for v in values}, key=lambda b: (-len(b), b)):
        if value in offsets:
            continue
        offset = len(pool)
        pool.extend(value + b'\0')
        for index in range(len(value)):
            offsets.setdefault(value[index:], offset + index)
    return pool, offsets


keys, key_offsets = string_pool(e[0] for e in ordered)
words, word_offsets = string_pool(e[1] for e in ordered)
assert len(keys) < 1 << 24 and len(words) < 1 << 24, 'Dictionary offset exceeds 24 bits'
assert all(0 <= entries[e] < 1 << 24 and 0 <= e[2] < 1 << 16 for e in ordered), 'Dictionary value exceeds packed format'
output = root / 'firmware/main/tab5_pinyin_dict.inc'
with output.open('w', encoding='utf-8', newline='\n') as stream:
    stream.write('// Generated by scripts/generate-pinyin-dict.py. Do not edit.\n')
    stream.write('// Derived from Rime/Android Pinyin IME, Apache-2.0; see ../third_party/rime-pinyin-simp.\n')
    for name, data in [('pinyin_keys', keys), ('pinyin_words', words)]:
        stream.write('static const char %s[] =\n' % name)
        for start in range(0, len(data), 32):
            stream.write('    "' + ''.join('\\%03o' % b for b in data[start:start + 32]) + '"\n')
        stream.write(';\n')
    stream.write('// Each row: key offset (24), word offset (24), weight (24), boundaries (16), little endian.\n')
    stream.write('static const uint8_t pinyin_dictionary[][11] = {\n')
    for key, word, boundaries in ordered:
        row = (key_offsets[key.encode()].to_bytes(3, 'little') + word_offsets[word.encode()].to_bytes(3, 'little') +
               entries[(key, word, boundaries)].to_bytes(3, 'little') + boundaries.to_bytes(2, 'little'))
        stream.write('    {' + ','.join(str(b) for b in row) + '},\n')
    stream.write('};\n')
print(f'PINYIN_DICTIONARY_OK entries={len(ordered)} keys={len(keys)} words={len(words)} rows={len(ordered) * 11} source_sha256={expected}')
