"""Generate compact LVGL ARGB8888 images from the official brand assets."""

from pathlib import Path
from struct import pack

from PIL import Image
from lz4.block import compress, decompress


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "firmware" / "assets" / "brands"
OUTPUT = ROOT / "firmware" / "main" / "brand_logos.h"
SIZE = 36
# Optical sizing shared by the overview and provider picker. Filled tiles need
# more breathing room than open marks; keep the same canvas and aspect ratios.
PROVIDER_FIT_SIZE = {
    "openai_option": 30,
    "claude": 34,
    "kimi": 32,
    "minimax": 32,
    "zhipu": 32,
    "stepfun": 32,
    "baidu": 32,
    "xiaomi": 32,
    "volcengine": 34,
}

lines = [
    "// Generated by scripts/generate-brand-logos.py. Do not edit by hand.",
    "#pragma once",
    '#include "lvgl.h"',
    "",
]
for name in ("openai", "deepseek", "zhipu", "codex", "codex_key", "doubao",
             "claude", "alibaba", "kimi", "minimax", "stepfun", "baidu", "xiaomi", "volcengine", "openai_option"):
    size = 144 if name == "doubao" else 128 if name == "codex_key" else SIZE
    source_name = {"codex_key": "codex", "doubao": "doubao-ime", "openai_option": "openai"}.get(name, name)
    with Image.open(ASSETS / f"{source_name}.png") as original:
        # Same pixel canvas/format for every provider. Preserve aspect ratio;
        # non-square future source assets must not stretch a brand mark.
        fitted = original.convert("RGBA")
        fit_size = PROVIDER_FIT_SIZE.get(name, size)
        if name == "openai_option":
            # The source has wide transparent margins; fit its visible mark
            # to a shared 30x29 visible mark for overview and model selection.
            bounds = fitted.getchannel("A").point(lambda alpha: 255 if alpha >= 8 else 0).getbbox()
            if not bounds:
                raise ValueError("OpenAI source has no visible mark")
            fitted = fitted.crop(bounds)
        fitted.thumbnail((fit_size, fit_size), Image.Resampling.LANCZOS)
        if max(fitted.size)<fit_size:
            scale=fit_size/max(fitted.size)
            fitted=fitted.resize((round(fitted.width*scale),round(fitted.height*scale)),Image.Resampling.LANCZOS)
        image=Image.new("RGBA",(size,size))
        image.paste(fitted,((size-fitted.width)//2,(size-fitted.height)//2))
    pixels = image.tobytes("raw", "BGRA")
    compressed = compress(pixels, mode="high_compression", compression=12, store_size=False)
    compressed_icon = len(compressed) + 12 < len(pixels)
    if compressed_icon:
        assert decompress(compressed, uncompressed_size=len(pixels)) == pixels
        pixels = pack("<III", 2, len(compressed), len(pixels)) + compressed
    flags = ", .flags = LV_IMAGE_FLAGS_COMPRESSED" if compressed_icon else ""
    lines.append(f"static const uint8_t brand_{name}_pixels[] __attribute__((aligned(4))) = {{")
    for start in range(0, len(pixels), 16):
        values = ", ".join(f"0x{value:02x}" for value in pixels[start : start + 16])
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            f"static const lv_image_dsc_t brand_{name}_image = {{",
            "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888" + flags + ",",
            f"               .w = {size}, .h = {size}, .stride = {size * 4}}},",
            f"    .data_size = sizeof(brand_{name}_pixels),",
            f"    .data = brand_{name}_pixels,",
            "};",
            "",
        ]
    )

OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {OUTPUT}")
