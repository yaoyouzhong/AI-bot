"""Pinned OFL serif subsets for the adaptive date screensaver."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
chars=set('0123456789 年月日还有已过去天就是今')
from collections import Counter
source=root/'firmware/third_party/rime-pinyin-simp/pinyin_simp.dict.yaml'
assert hashlib.sha256(source.read_bytes()).hexdigest()=='e341598343a0f0f2035bb1aafc34a7f3bb7887deeecb3f60796262aaa2983e6b'
frequency=Counter()
for line in source.read_text(encoding='utf-8').splitlines():
    fields=line.split('\t')
    if len(fields)!=3 or not fields[2].isdigit():continue
    word,_,weight=fields
    try:word.encode('gb2312')
    except UnicodeEncodeError:continue
    for ch in word:frequency[ch]+=int(weight)
title=set(chr(c) for c in range(32,127))|set(sorted(frequency,key=lambda c:(-frequency[c],c))[:1000])
# Event-name vocabulary supplements the frequency subset, independent of preview fixtures.
title.update('硕士博士研究生招生考试赴约生日纪念结婚毕业旅行出发开学项目上线发布答辩签约周年元旦春节中秋端午清明放假高考中考公务员资格驾照合同搬家新房交付还款信用卡活动会议工作计划比赛演唱音乐休假退休倒计时')
# Store scalable outlines once, instead of enlarging a small bitmap font.
from fontTools import subset
from fontTools.ttLib import TTFont
font=root/'.tools/font-builder/date-serif/NotoSerifCJKsc-Bold.otf'
assert hashlib.sha256(font.read_bytes()).hexdigest()=='8af07d4b6c2e82bcc72a30e066eaf295f11b9424f4aad2eaa9fe0e9c3b38fc73'
face=TTFont(font,recalcTimestamp=False)
options=subset.Options();options.hinting=False;options.layout_features=[];options.recalc_timestamp=False
options.name_IDs=[0,1,2,3,4,5,6,13,14]
sub=subset.Subsetter(options=options);sub.populate(text=''.join(sorted(title|chars)));sub.subset(face)
# Rename the derivative while retaining the copyright and OFL records.
for record in face['name'].names:
    if record.nameID in (1,3,4,6):record.string=('Tab5 Date Serif' if record.nameID!=6 else 'Tab5DateSerif').encode(record.getEncoding())
output=root/'.tools/font-builder/date-serif/tab5-date-serif.otf';face.save(output)
data=output.read_bytes()
lines=['/* Generated by scripts/generate-date-saver-font.py; SIL OFL 1.1. */','#include <stddef.h>','#include <stdint.h>','const uint8_t tab5_date_serif_data[] = {']
lines.extend('    '+','.join(f'0x{v:02x}' for v in data[i:i+20])+',' for i in range(0,len(data),20))
lines+=['};',f'const size_t tab5_date_serif_size = {len(data)};']
(root/'firmware/main/tab5_date_serif_data.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('DATE_VECTOR_FONT_OK',len(data),hashlib.sha256(data).hexdigest())
