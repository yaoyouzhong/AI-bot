"""Host-only timing regressions and an optional, unapplied .234 review patch.

This never builds a firmware image, accesses a device or alters firmware sources.
The reference helper is original AI-bot code. The optional archive is the
maintainer's published source, identified in MAC-TAB5-MUSIC-TIMING-FOLLOWUP.md.
"""
import argparse
import difflib
import hashlib
import json
import subprocess
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "scripts/mac_tab5_interop"
SOURCE_SHA = "c107e5f929e757a6342bea659f84e726a40d5f16b692441865f348fa26290890"
OLD = '''    int duration = (int)num(m, "durationSeconds"), pos = (int)num(m, "elapsedSeconds");
    bool timeline_available=!cJSON_IsFalse(item(m,"timelineAvailable"));
    if (timeline_available && fresh && yes(m, "playing") && (duration > 0 || pos > 0))
        pos += (int)((now - last_received) / 1000);
    if (pos < 0)
        pos = 0;
    if (duration > 0 && pos > duration)
        pos = duration;
'''
NEW = '''    double seconds=num(m,"elapsedSeconds"),length=num(m,"durationSeconds");
    cJSON *input=item(shown,"pcInput");
    uint64_t session=aibot_music_key(text(input,"session"),"","");
    uint64_t track=aibot_music_key(text(m,"title"),text(m,"artist"),text(m,"album"));
    double seq=num(input,"sequence");
    uint64_t sequence=isfinite(seq)&&seq>0&&seq<=9007199254740991.0?(uint64_t)seq:0;
    aibot_music_position position=aibot_music_value(&music_clock,session,track,sequence,
        seconds,length,yes(m,"playing"),!cJSON_IsFalse(item(m,"timelineAvailable")),
        fresh,last_received,now);
    int duration=isfinite(length)&&length>0&&length<=1e9?(int)length:0;
    int pos=(int)(position.milliseconds/1000);
    bool timeline_available=position.available;
'''


def review_patch(archive, output):
    if hashlib.sha256(archive.read_bytes()).hexdigest() != SOURCE_SHA:
        raise ValueError("Source archive SHA mismatch; no patch generated")
    with zipfile.ZipFile(archive) as bundle:
        before = bundle.read("source/firmware/main/ui.c").decode("utf-8")
    replacements = [
        ('#include "ui_time.h"\n', '#include "ui_time.h"\n#include "ui_music_timeline.h"\nstatic aibot_music_clock music_clock;\n'),
        ('    if(!music_has_track())return;\n', '    if(!music_has_track()){music_clock=(aibot_music_clock){0};return;}\n'),
        (OLD, NEW),
    ]
    after = before
    for old, new in replacements:
        if "\r\n" in before:
            old, new = old.replace("\n", "\r\n"), new.replace("\n", "\r\n")
        if after.count(old) != 1:
            raise ValueError("Reviewed source context mismatch; no patch generated")
        after = after.replace(old, new)
    header = (REFERENCE / "music_timeline_reference.h").read_text(encoding="utf-8")
    patch = "".join(difflib.unified_diff(before.splitlines(True), after.splitlines(True),
        fromfile="a/main/ui.c", tofile="b/main/ui.c"))
    patch += "".join(difflib.unified_diff([], header.splitlines(True),
        fromfile="/dev/null", tofile="b/main/ui_music_timeline.h"))
    # Apply only to a disposable copy, verifying both the exact context and
    # generated bytes. The supplied ZIP and all existing projects stay intact.
    with tempfile.TemporaryDirectory(prefix="aibot-music-review-") as directory:
        stage = Path(directory)
        (stage / "main").mkdir()
        (stage / "main/ui.c").write_bytes(before.encode("utf-8"))
        subprocess.run(["git", "apply", "--check", "-"], input=patch, cwd=stage, text=True, check=True)
        subprocess.run(["git", "apply", "-"], input=patch, cwd=stage, text=True, check=True)
        assert (stage / "main/ui.c").read_bytes() == after.encode("utf-8")
        assert (stage / "main/ui_music_timeline.h").read_text(encoding="utf-8") == header
    (output / "tab5-0.2.234-music-timing-review.patch").write_text(patch, encoding="utf-8")
    return "exact archive/context verified; applies only to disposable source copy"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--firmware-source", type=Path)
    parser.add_argument("--address-sanitizer", action="store_true", help="Also enable ASan on a supported host toolchain")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    binary = args.output.resolve() / "music-reference"
    sanitizer = "address,undefined" if args.address_sanitizer else "undefined"
    subprocess.run(["cc", "-std=c11", "-Wall", "-Wextra", "-Werror", "-fsanitize=" + sanitizer,
        str(REFERENCE / "music_timeline_reference.c"), "-lm", "-o", str(binary)], check=True)
    result = subprocess.run([str(binary)], capture_output=True, text=True, check=True, timeout=15)
    print(result.stdout, end="")
    report = dict(kind="synthetic host C reference", sanitizer=sanitizer,
        firmwareBuild="not performed", device="not accessed", patch="not requested", output=result.stdout.splitlines())
    if args.firmware_source:
        report["patch"] = review_patch(args.firmware_source, args.output)
        report["sourceSHA256"] = SOURCE_SHA
        print("MUSIC_REVIEW_PATCH_OK exact .234 archive; unapplied; firmware build and hardware acceptance pending")
    (args.output / "verification.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
