"""Extract the exact three Font Awesome glyph outlines used by TAB5's LVGL font."""
import argparse,hashlib
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
class Pen(BasePen):
 def __init__(self,gs):super().__init__(gs);self.lines=[];self.pos=None
 def pt(self,p):return ','.join(f'{v:g}f' for v in p)
 def _moveTo(self,p):self.lines.append('p.StartFigure();');self.pos=p
 def _lineTo(self,p):self.lines.append(f'p.AddLine({self.pt(self.pos)},{self.pt(p)});');self.pos=p
 def _curveToOne(self,a,b,c):self.lines.append(f'p.AddBezier({self.pt(self.pos)},{self.pt(a)},{self.pt(b)},{self.pt(c)});');self.pos=c
 def _closePath(self):self.lines.append('p.CloseFigure();')
def build(source,output):
 f=TTFont(source);gs=f.getGlyphSet();lines=['// Generated by scripts/extract_tab5_transport_icons.py.','// Font Awesome glyphs via LVGL; Copyright Font Awesome. SIL OFL 1.1.','// Input SHA-256: '+hashlib.sha256(source.read_bytes()).hexdigest(),'using System.Drawing.Drawing2D;','namespace AIBotBridge;','internal static class Tab5TransportGlyphs {','internal static GraphicsPath Create(int symbol){var p=new GraphicsPath(FillMode.Winding);switch(symbol){']
 for i,code in enumerate((0xf287,0xf1eb,0xf293)):
  pen=Pen(gs);gs[f.getBestCmap()[code]].draw(pen);lines+=['case '+str(i)+':']+pen.lines+['break;']
 lines+=['}return p;}','}'];output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('output',type=Path);a=p.parse_args();build(a.source,a.output)
